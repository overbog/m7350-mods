// Generates src/font8x14.h: printable ASCII (32..126) as 1-bit 8x14 glyphs,
// rendered from Menlo with antialiasing off. Run: swift tools/gen-font.swift > src/font8x14.h
import CoreGraphics
import CoreText
import Foundation

let w = 8, h = 14
let font = CTFontCreateWithName("Menlo-Regular" as CFString, 12, nil)
let descent = CTFontGetDescent(font)
var out = "/* Generated by tools/gen-font.swift (Menlo 12, 8x14, 1 bpp). Do not edit. */\n"
out += "static const unsigned char font8x14[95][14] = {\n"
for code in 32...126 {
    let ctx = CGContext(data: nil, width: w, height: h, bitsPerComponent: 8, bytesPerRow: w,
                        space: CGColorSpaceCreateDeviceGray(), bitmapInfo: CGImageAlphaInfo.none.rawValue)!
    ctx.setFillColor(gray: 0, alpha: 1); ctx.fill(CGRect(x: 0, y: 0, width: w, height: h))
    ctx.setShouldAntialias(false); ctx.setAllowsAntialiasing(false)
    ctx.setShouldSmoothFonts(false)
    let s = String(UnicodeScalar(UInt8(code)))
    let attr = NSAttributedString(string: s, attributes: [
        kCTFontAttributeName as NSAttributedString.Key: font,
        kCTForegroundColorFromContextAttributeName as NSAttributedString.Key: true])
    ctx.setFillColor(gray: 1, alpha: 1)
    let line = CTLineCreateWithAttributedString(attr)
    ctx.textPosition = CGPoint(x: 0.4, y: ceil(descent) + 0.5)
    CTLineDraw(line, ctx)
    let px = ctx.data!.bindMemory(to: UInt8.self, capacity: w * h)
    var rows: [String] = []
    for y in 0..<h {            // bitmap row 0 is the top in memory
        var b = 0
        for x in 0..<w where px[y * w + x] > 127 { b |= 0x80 >> x }
        rows.append(String(format: "0x%02x", b))
    }
    let label = code == 92 ? "backslash" : (code == 47 ? "slash" : s)
    out += "  {" + rows.joined(separator: ",") + "}, /* \(label) */\n"
}
out += "};\n"
print(out, terminator: "")
