#!/usr/bin/env python3
"""Check the ARM runtime's metadata and imports without loading modules."""

import argparse
import hashlib
from pathlib import Path
import re
import struct
import subprocess

from build import MODULES, TOOLS

VERMAGIC = "3.18.20 preempt mod_unload ARMv7 p2v8"


def tool(*args):
    return subprocess.check_output(args, text=True)


def require(condition, message):
    if not condition:
        raise SystemExit(message)


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def without_build_id(path):
    """Mask the GNU build ID section in an ELF32 little-endian file."""
    data = bytearray(path.read_bytes())
    section_offset, = struct.unpack_from("<I", data, 32)
    entry_size, count, string_index = struct.unpack_from("<HHH", data, 46)
    if not count:
        return data
    strings_offset, strings_size = struct.unpack_from(
        "<II", data, section_offset + entry_size * string_index + 16)
    strings = data[strings_offset:strings_offset + strings_size]
    for index in range(count):
        start = section_offset + entry_size * index
        name_offset, = struct.unpack_from("<I", data, start)
        if strings[name_offset:].startswith(b".note.gnu.build-id\0"):
            offset, size = struct.unpack_from("<II", data, start + 16)
            data[offset:offset + size] = bytes(size)
            break
    return data


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("runtime", type=Path)
    parser.add_argument("symvers", type=Path, help="OEM symbols generated by the source build")
    parser.add_argument("--bench", type=Path, help="Optional retained bench runtime for comparison")
    args = parser.parse_args()
    modules = [args.runtime / f"ko/{name}.ko" for name in MODULES]
    executables = [args.runtime / f"bin/{name}" for name in TOOLS]
    dropbear = args.runtime / "bin/dropbearmulti"
    if dropbear.exists():
        executables.append(dropbear)

    known = {line.split()[1] for line in args.symvers.read_text().splitlines()}
    for path in modules:
        exports = set(re.findall(r"\b__ksymtab_(\w+)$", tool("nm", "--defined-only", path),
                                 re.MULTILINE))
        require(not exports & known, f"{path.name}: duplicate exports: {sorted(exports & known)}")
        known.update(exports)
    for path in modules + executables:
        header = tool("readelf", "-h", path)
        require(re.search(r"Machine:\s+ARM\s*$", header, re.MULTILINE)
                and re.search(r"Class:\s+ELF32\s*$", header, re.MULTILINE)
                and "Version5 EABI" in header and "little endian" in header,
                f"{path.name}: expected ARM ELF32 little-endian EABI5")
        if path in modules:
            metadata = tool("readelf", "-p", ".modinfo", path)
            require(f"vermagic={VERMAGIC}" in metadata, f"{path.name}: wrong vermagic")
            require("license=GPL" in metadata, f"{path.name}: unexpected module license tag")
            imports = set(re.findall(r"^\s+U\s+(\w+)$", tool("nm", "--undefined-only", path),
                                     re.MULTILINE))
            require(not imports - known,
                    f"{path.name}: unresolved imports: {sorted(imports - known)}")
            if path.name.startswith("rtl8192es-"):
                require("alias=sdio:c*v024Cd818B*" in metadata, f"{path.name}: wrong SDIO alias")
                slots = 2 if path.name.endswith("two-vap.ko") else 1
                raw = path.read_bytes()
                require(b"%s-va%d" in raw and b"optional VAP %d" in raw,
                        f"{path.name}: missing VAP format or fallback diagnostics")
                print(f"{path.name}: SDIO alias, VAP code, audited source configuration for {slots} slot(s)")
        elif path != dropbear:
            require("INTERP" not in tool("readelf", "-l", path),
                    f"{path.name}: unexpected ELF interpreter")
        if args.bench:
            name = path.relative_to(args.runtime)
            old = args.bench / name
            if old.is_file():
                if digest(old) == digest(path):
                    match = "identical"
                elif without_build_id(old) == without_build_id(path):
                    match = "only GNU build ID differs"
                else:
                    match = "different"
                print(f"{name}: {match} ({path.stat().st_size} bytes)")

    print(f"PASS: {len(modules)} ARM modules, {len(executables)} programs, closed module imports")


if __name__ == "__main__":
    main()
